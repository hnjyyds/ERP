def _role_permissions(
    *, role_id: str, id_prefix: str, permission_ids: list[str]
) -> list[RolePermission]:
    return [
        RolePermission(
            id=f"rp-{id_prefix}-{permission_id.removeprefix('perm-')}",
            role_id=role_id,
            permission_id=permission_id,
        )
        for permission_id in permission_ids
    ]
