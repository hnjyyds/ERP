import { Button, Input, Modal, Select } from 'antd'

import { freightMethodOptions } from '@/shared/formOptions'
import { FormSelect } from '@/shared/ui'
import { t } from '@/app/appI18n'
import type { Customer, ExportQuotation } from '@/api'

import { renderCustomerOptions } from '../exportQuotationHelpers'
import type { useExportQuotationWorkflow } from '../hooks/useExportQuotationWorkflow'

type Props = {
  workflow: ReturnType<typeof useExportQuotationWorkflow>
  customers: Customer[]
  loadingCustomers: boolean
  selectedQuotation: ExportQuotation | null
}

export function ExportQuotationFormModal({
  workflow,
  customers,
  loadingCustomers,
  selectedQuotation,
}: Props) {
  const { form } = workflow

  return (
    <Modal
      destroyOnHidden
      footer={null}
      open={workflow.formOpen}
      title={t('sales.quotation.form.title')}
      width={920}
      onCancel={workflow.closeQuotationForm}
    >
      <form className="record-form modal-record-form" onSubmit={workflow.submitQuotation}>
        <div className="form-pair two">
          <label>
            {t('sales.quotation.field.code')}
            <Input
              readOnly
              value={form.code}
              placeholder={t('sales.quotation.form.codeAutoGenerated')}
            />
          </label>
          <label>
            {t('sales.quotation.field.quoteDate')}
            <Input
              type="date"
              value={form.quote_date}
              onChange={(event) => workflow.setForm({ ...form, quote_date: event.target.value })}
            />
          </label>
        </div>
        <div className="form-pair two">
          <label>
            {t('sales.quotation.form.selectCustomer')}
            <Select
              allowClear
              showSearch
              loading={loadingCustomers}
              value={form.customer_id || undefined}
              placeholder={
                customers.length > 0
                  ? t('sales.quotation.form.customerSelectPlaceholder')
                  : t('sales.quotation.form.customerMissing')
              }
              optionFilterProp="label"
              notFoundContent={
                loadingCustomers
                  ? t('sales.quotation.list.loadingCustomers')
                  : t('sales.quotation.list.noCustomers')
              }
              onChange={workflow.applyCustomerToQuotationForm}
            >
              {renderCustomerOptions(customers)}
            </Select>
          </label>
          <label>
            {t('sales.quotation.field.customerId')}
            <Input
              value={form.customer_id}
              readOnly
              placeholder={t('sales.quotation.form.customerNamePlaceholder')}
            />
          </label>
        </div>
        <label>
          {t('sales.quotation.field.customerName')}
          <Input
            value={form.customer_name}
            readOnly
            placeholder={t('sales.quotation.form.customerNamePlaceholder')}
          />
        </label>
        <div className="form-pair two">
          <label>
            {t('sales.quotation.field.salesperson')}
            <Input
              value={form.sales_user_name}
              onChange={(event) =>
                workflow.setForm({ ...form, sales_user_name: event.target.value })
              }
            />
          </label>
          <label>
            {t('sales.quotation.field.currency')}
            <Input
              value={form.currency}
              onChange={(event) => workflow.setForm({ ...form, currency: event.target.value })}
            />
          </label>
        </div>
        <div className="form-pair two">
          <label>
            {t('sales.quotation.field.tradeTerm')}
            <Input
              value={form.trade_term}
              onChange={(event) => workflow.setForm({ ...form, trade_term: event.target.value })}
            />
          </label>
          <label>
            {t('sales.quotation.field.validUntil')}
            <Input
              type="date"
              value={form.valid_until}
              onChange={(event) => workflow.setForm({ ...form, valid_until: event.target.value })}
            />
          </label>
        </div>
        <label>
          {t('sales.quotation.field.description')}
          <Input.TextArea
            rows={2}
            value={form.description}
            onChange={(event) => workflow.setForm({ ...form, description: event.target.value })}
          />
        </label>
        <div className="form-divider">{t('sales.quotation.form.linesTitle')}</div>
        <div className="form-pair two">
          <label>
            {t('sales.quotation.field.productId')}
            <Input
              value={form.product_id}
              onChange={(event) => workflow.setForm({ ...form, product_id: event.target.value })}
            />
          </label>
          <label>
            {t('sales.quotation.field.productCode')}
            <Input
              value={form.product_code}
              onChange={(event) => workflow.setForm({ ...form, product_code: event.target.value })}
            />
          </label>
        </div>
        <label>
          {t('sales.quotation.field.productName')}
          <Input
            value={form.product_name}
            onChange={(event) => workflow.setForm({ ...form, product_name: event.target.value })}
          />
        </label>
        <div className="form-pair two">
          <label>
            {t('sales.quotation.field.specification')}
            <Input
              value={form.specification}
              onChange={(event) =>
                workflow.setForm({ ...form, specification: event.target.value })
              }
            />
          </label>
          <label>
            {t('sales.quotation.field.model')}
            <Input
              value={form.model}
              onChange={(event) => workflow.setForm({ ...form, model: event.target.value })}
            />
          </label>
        </div>
        <div className="form-pair three">
          <label>
            {t('sales.quotation.field.quantity')}
            <Input
              type="number"
              min="0.0001"
              step="0.0001"
              value={form.quantity}
              onChange={(event) => workflow.setForm({ ...form, quantity: event.target.value })}
            />
          </label>
          <label>
            {t('sales.quotation.field.unit')}
            <Input
              value={form.unit}
              onChange={(event) => workflow.setForm({ ...form, unit: event.target.value })}
            />
          </label>
          <label>
            {t('sales.quotation.field.unitPrice')}
            <Input
              type="number"
              min="0.0001"
              step="0.0001"
              value={form.unit_price}
              onChange={(event) => workflow.setForm({ ...form, unit_price: event.target.value })}
            />
          </label>
        </div>
        <div className="form-pair two">
          <label>
            {t('sales.quotation.field.freightMethod')}
            <FormSelect
              value={form.freight_method}
              onChange={(event) =>
                workflow.setForm({ ...form, freight_method: event.target.value })
              }
            >
              {freightMethodOptions.map((item) => (
                <option key={item.value} value={item.value}>
                  {t(item.labelKey)}
                </option>
              ))}
            </FormSelect>
          </label>
          <label>
            {t('sales.quotation.field.freightAmount')}
            <Input
              type="number"
              min="0"
              step="0.01"
              value={form.freight_amount}
              onChange={(event) =>
                workflow.setForm({ ...form, freight_amount: event.target.value })
              }
            />
          </label>
        </div>
        <div className="form-pair two">
          <label>
            {t('sales.quotation.field.purchaseReferenceSupplier')}
            <Input
              value={form.purchase_reference_supplier_name}
              onChange={(event) =>
                workflow.setForm({
                  ...form,
                  purchase_reference_supplier_name: event.target.value,
                })
              }
            />
          </label>
          <label>
            {t('sales.quotation.field.purchaseReferencePrice')}
            <Input
              type="number"
              min="0"
              step="0.0001"
              value={form.purchase_reference_price}
              onChange={(event) =>
                workflow.setForm({ ...form, purchase_reference_price: event.target.value })
              }
            />
          </label>
        </div>
        <label>
          {t('sales.quotation.field.lineRemark')}
          <Input
            value={form.line_remark}
            onChange={(event) => workflow.setForm({ ...form, line_remark: event.target.value })}
          />
        </label>
        <div className="modal-actions">
          <Button onClick={workflow.closeQuotationForm}>{t('common.cancel')}</Button>
          <Button
            disabled={
              !selectedQuotation ||
              !['draft', 'rejected'].includes(selectedQuotation.approval_status)
            }
            loading={workflow.submitting}
            onClick={() => void workflow.saveQuotationDraft()}
          >
            {t('sales.quotation.action.saveDraft')}
          </Button>
          <Button htmlType="submit" loading={workflow.submitting} type="primary">
            {t('sales.quotation.action.create')}
          </Button>
        </div>
      </form>
    </Modal>
  )
}
