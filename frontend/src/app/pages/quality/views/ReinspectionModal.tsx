import { Alert, Button, Input, Modal } from 'antd'

import { t } from '@/app/appI18n'

import type { useReinspection } from '../hooks/useReinspection'
import { RequiredFieldLabel } from './QualityFormFields'

type Props = {
  model: ReturnType<typeof useReinspection>
}

export function ReinspectionModal({ model }: Props) {
  return (
    <Modal
      centered
      footer={null}
      open={model.reinspectionOpen}
      title={t('quality.inspection.modal.reinspectionTitle')}
      width={620}
      onCancel={model.closeReinspection}
    >
      <form className="record-form" onSubmit={model.submitReinspection}>
        <Alert showIcon title={t('quality.inspection.modal.reinspectionNotice')} type="info" />
        <label htmlFor="quality-reinspection-code">
          <span>{t('quality.inspection.field.reinspectionCode')}</span>
          <Input
            id="quality-reinspection-code"
            readOnly
            value={model.reinspectionCode}
            placeholder={t('quality.inspection.form.codeAutoGenerated')}
          />
        </label>
        <label htmlFor="quality-reinspection-schedule">
          <RequiredFieldLabel>
            {t('quality.inspection.field.reinspectionSchedule')}
          </RequiredFieldLabel>
          <Input
            id="quality-reinspection-schedule"
            required
            type="datetime-local"
            value={model.reinspectionSchedule}
            onChange={(event) => model.setReinspectionSchedule(event.target.value)}
          />
        </label>
        <label htmlFor="quality-reinspection-reason">
          <RequiredFieldLabel>
            {t('quality.inspection.field.reinspectionReason')}
          </RequiredFieldLabel>
          <Input.TextArea
            id="quality-reinspection-reason"
            required
            rows={3}
            value={model.reinspectionReason}
            onChange={(event) => model.setReinspectionReason(event.target.value)}
          />
        </label>
        <Button htmlType="submit" loading={model.submitting} type="primary">
          {t('quality.inspection.modal.submitReinspection')}
        </Button>
      </form>
    </Modal>
  )
}
