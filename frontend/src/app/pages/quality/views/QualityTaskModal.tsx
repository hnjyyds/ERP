import { Alert, Button, Input, Modal, Select } from 'antd'
import { ShieldCheck } from 'lucide-react'

import { PanelTitle, RemoteSelect } from '@/shared/ui'
import { t } from '@/app/appI18n'

import {
  assignableUserOptionLabel,
  fieldLabels,
} from '../qualityInspectionMeta'
import type { useQualityTaskModal } from '../hooks/useQualityTaskModal'
import { FieldError, RequiredFieldLabel } from './QualityFormFields'

type Props = {
  model: ReturnType<typeof useQualityTaskModal>
}

export function QualityTaskModal({ model }: Props) {
  return (
    <Modal
      centered
      className="quality-task-modal"
      footer={[
        <Button key="cancel" onClick={model.cancelTaskModal}>
          {t('common.cancel')}
        </Button>,
        <Button
          key="submit"
          form="quality-task-form"
          htmlType="submit"
          loading={model.taskSubmitting}
          type="primary"
        >
          {t('quality.inspection.modal.submitCreate')}
        </Button>,
      ]}
      open={model.taskModalOpen}
      title={t('quality.inspection.modal.createTitle')}
      width={860}
      onCancel={model.cancelTaskModal}
    >
      <div className="workflow-modal-content entity-modal-form">
        <div className="panel-heading quality-form-heading">
          <PanelTitle
            icon={<ShieldCheck size={18} />}
            title={t('quality.inspection.modal.formHeading')}
          />
        </div>
        <Alert
          showIcon
          title={t('quality.inspection.modal.noticeTitle')}
          description={t('quality.inspection.modal.noticeDescription')}
          type="info"
        />
        <form
          className="record-form"
          id="quality-task-form"
          noValidate
          onSubmit={model.createTask}
        >
          {model.validationEntries.length > 0 ? (
            <Alert
              className="quality-form-validation-summary"
              description={
                <ul className="quality-form-validation-list">
                  {model.validationEntries.map(({ field, message: errorMessage }) => (
                    <li key={field}>
                      <button type="button" onClick={() => model.focusField(field)}>
                        {t('quality.inspection.validation.item', {
                          field: t(fieldLabels[field]),
                          message: errorMessage,
                        })}
                      </button>
                    </li>
                  ))}
                </ul>
              }
              showIcon
              title={t('quality.inspection.validation.summaryTitle', {
                count: model.validationEntries.length,
              })}
              type="error"
            />
          ) : null}

          <div className="form-divider">{t('quality.inspection.modal.taskSection')}</div>
          <div className="form-pair two">
            <label htmlFor="quality-code">
              <span>{t('quality.inspection.field.code')}</span>
              <Input
                id="quality-code"
                readOnly
                value={model.form.code}
                placeholder={t('quality.inspection.form.codeAutoGenerated')}
              />
            </label>
            <label htmlFor="quality-contract-id">
              <RequiredFieldLabel>{t('quality.inspection.field.contract')}</RequiredFieldLabel>
              <RemoteSelect
                ariaDescribedBy={
                  model.fieldErrors.purchase_contract_id ? 'quality-contract-id-error' : undefined
                }
                ariaInvalid={Boolean(model.fieldErrors.purchase_contract_id)}
                ariaLabel={t('quality.inspection.field.contract')}
                fetchOptions={model.fetchContractOptions}
                id="quality-contract-id"
                placeholder={t('quality.inspection.modal.contractPlaceholder')}
                required
                status={model.fieldErrors.purchase_contract_id ? 'error' : undefined}
                value={model.form.purchase_contract_id || null}
                onChange={(value) => model.updateFormField('purchase_contract_id', value)}
              />
              <FieldError
                field="purchase_contract_id"
                message={model.fieldErrors.purchase_contract_id}
              />
            </label>
          </div>

          <div className="form-pair two">
            <label htmlFor="quality-scheduled-at">
              <RequiredFieldLabel>{t('quality.inspection.field.scheduledAt')}</RequiredFieldLabel>
              <Input
                aria-describedby={
                  model.fieldErrors.scheduled_at ? 'quality-scheduled-at-error' : undefined
                }
                aria-invalid={Boolean(model.fieldErrors.scheduled_at)}
                id="quality-scheduled-at"
                required
                status={model.fieldErrors.scheduled_at ? 'error' : undefined}
                type="datetime-local"
                value={model.form.scheduled_at}
                onInput={(event) => model.updateFormField('scheduled_at', event.currentTarget.value)}
              />
              <FieldError field="scheduled_at" message={model.fieldErrors.scheduled_at} />
            </label>
            <label htmlFor="quality-inspector-id">
              <RequiredFieldLabel>{t('quality.inspection.field.inspector')}</RequiredFieldLabel>
              <Select
                aria-describedby={
                  model.fieldErrors.inspector_id ? 'quality-inspector-id-error' : undefined
                }
                aria-invalid={Boolean(model.fieldErrors.inspector_id)}
                aria-label={t('quality.inspection.field.inspector')}
                aria-required="true"
                id="quality-inspector-id"
                loading={model.loadingAssignableUsers}
                notFoundContent={
                  model.loadingAssignableUsers
                    ? t('quality.inspection.modal.inspectorLoading')
                    : t('quality.inspection.modal.inspectorEmpty')
                }
                optionFilterProp="label"
                placeholder={
                  model.loadingAssignableUsers
                    ? t('quality.inspection.modal.inspectorPlaceholderLoading')
                    : t('quality.inspection.modal.inspectorPlaceholder')
                }
                showSearch
                status={model.fieldErrors.inspector_id ? 'error' : undefined}
                value={model.form.inspector_id || undefined}
                onChange={model.applyInspector}
              >
                {model.form.inspector_id &&
                !model.assignableUsers.some((user) => user.id === model.form.inspector_id) ? (
                  <Select.Option
                    key={model.form.inspector_id}
                    disabled
                    label={`${model.form.inspector_name} / ${t('quality.inspection.field.currentUser')}`}
                    value={model.form.inspector_id}
                  >
                    {model.form.inspector_name} / {t('quality.inspection.field.currentUser')}
                  </Select.Option>
                ) : null}
                {model.assignableUsers.map((user) => {
                  const label = assignableUserOptionLabel(user)
                  return (
                    <Select.Option key={user.id} label={label} value={user.id}>
                      {label}
                    </Select.Option>
                  )
                })}
              </Select>
              <FieldError field="inspector_id" message={model.fieldErrors.inspector_id} />
            </label>
          </div>

          <label htmlFor="quality-task-note">
            {t('quality.inspection.field.taskNote')}
            <Input.TextArea
              id="quality-task-note"
              placeholder={t('quality.inspection.modal.taskNotePlaceholder')}
              rows={3}
              value={model.form.task_note}
              onChange={(event) =>
                model.setForm((current) => ({ ...current, task_note: event.target.value }))
              }
            />
          </label>
          <label htmlFor="quality-attachment-group">
            {t('quality.inspection.field.attachmentGroup')}
            <Input
              id="quality-attachment-group"
              value={model.form.attachment_group_id}
              onChange={(event) =>
                model.setForm((current) => ({
                  ...current,
                  attachment_group_id: event.target.value,
                }))
              }
            />
          </label>
        </form>
      </div>
    </Modal>
  )
}
