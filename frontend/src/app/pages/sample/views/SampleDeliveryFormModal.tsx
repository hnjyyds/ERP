import { Input, Modal } from 'antd'
import type { FormEvent } from 'react'
import { useState } from 'react'
import { t } from '@/app/appI18n'
import { FormSelect, RemoteSelect } from '@/shared/ui'
import {
  sampleDeliveryFeeTypeOptions,
  sampleDeliveryPayerTypeOptions,
} from '@/shared/formOptions'
import { sampleRecordTypeLabel } from '../sampleDeliveryHelpers'
import type { SampleDeliveryFormState } from '../sampleDeliveryHelpers'
import { useSampleFormOptions } from '../hooks/useSampleFormOptions'

type Props = {
  open: boolean
  mode: 'create' | 'edit' | null
  form: SampleDeliveryFormState
  submitting: boolean
  onFormChange: (form: SampleDeliveryFormState) => void
  onClose: () => void
  onCreate: (event: FormEvent<HTMLFormElement>) => void
  onSaveDraft: () => void
}

export function SampleDeliveryFormModal({
  open,
  mode,
  form,
  submitting,
  onFormChange,
  onClose,
  onCreate,
  onSaveDraft,
}: Props) {
  const { fetchQuotations, fetchSampleRecords, getQuotation, getSampleRecord } =
    useSampleFormOptions(form.customer_id)
  const [selectedRecord, setSelectedRecord] = useState<
    ReturnType<typeof getSampleRecord>
  >(null)

  function handleQuotationChange(value: string) {
    if (!value) {
      onFormChange({ ...form, quotation_id: '', quotation_no: '' })
      return
    }
    const quotation = getQuotation(value)
    onFormChange({
      ...form,
      quotation_id: value,
      quotation_no: quotation?.code ?? (form.quotation_id === value ? form.quotation_no : ''),
    })
  }

  function handleSampleRecordChange(value: string) {
    if (!value) {
      setSelectedRecord(null)
      onFormChange({
        ...form,
        sample_record_id: '',
        sample_code: '',
        product_id: '',
        product_code: '',
        product_name: '',
      })
      return
    }
    const record = getSampleRecord(value)
    setSelectedRecord(record)
    if (!record) {
      onFormChange({ ...form, sample_record_id: value })
      return
    }
    onFormChange({
      ...form,
      sample_record_id: record.id,
      sample_code: record.code,
      sample_type: record.sample_type,
      product_id: record.product_id ?? '',
      product_code: record.product_code ?? '',
      product_name: record.product_name,
      unit: record.unit,
    })
  }

  return (
    <Modal
      centered
      footer={null}
      open={open}
      title={
        mode === 'edit'
          ? t('sample.delivery.modal.editTitle')
          : t('sample.delivery.modal.createTitle')
      }
      width={1040}
      onCancel={onClose}
    >
      <form
        className="record-form entity-modal-form sample-modal-form"
        onSubmit={
          mode === 'edit'
            ? (event) => {
                event.preventDefault()
                onSaveDraft()
              }
            : onCreate
        }
      >
        <div className="form-pair two">
          <label>
            {t('sample.delivery.field.code')}
            <Input
              readOnly
              value={form.code}
              placeholder={t('sample.delivery.form.codeAutoGenerated')}
            />
          </label>
          <label>
            {t('sample.delivery.field.deliveryDate')}
            <Input
              type="date"
              value={form.delivery_date}
              onChange={(event) => onFormChange({ ...form, delivery_date: event.target.value })}
            />
          </label>
        </div>
        <div className="form-pair two">
          <label>
            {t('sample.delivery.field.customerId')}
            <Input
              value={form.customer_id}
              onChange={(event) => onFormChange({ ...form, customer_id: event.target.value })}
            />
          </label>
          <label>
            {t('sample.delivery.field.customerName')}
            <Input
              value={form.customer_name}
              onChange={(event) => onFormChange({ ...form, customer_name: event.target.value })}
            />
          </label>
        </div>
        <div className="form-pair two">
          <label>
            {t('sample.delivery.field.supplier')}
            <Input
              value={form.supplier_name}
              onChange={(event) => onFormChange({ ...form, supplier_name: event.target.value })}
            />
          </label>
          <label>
            {t('sample.delivery.field.factory')}
            <Input
              value={form.factory_name}
              onChange={(event) => onFormChange({ ...form, factory_name: event.target.value })}
            />
          </label>
        </div>
        <div className="form-pair two">
          <label>
            {t('sample.delivery.field.recipientName')}
            <Input
              value={form.recipient_name}
              onChange={(event) => onFormChange({ ...form, recipient_name: event.target.value })}
            />
          </label>
          <label>
            {t('sample.delivery.field.recipientCompany')}
            <Input
              value={form.recipient_company}
              onChange={(event) => onFormChange({ ...form, recipient_company: event.target.value })}
            />
          </label>
        </div>
        <label>
          {t('sample.delivery.field.recipientAddress')}
          <Input
            value={form.recipient_address}
            onChange={(event) => onFormChange({ ...form, recipient_address: event.target.value })}
          />
        </label>
        <div className="form-pair two">
          <label>
            {t('sample.delivery.field.expressCompany')}
            <Input
              value={form.express_company}
              onChange={(event) => onFormChange({ ...form, express_company: event.target.value })}
            />
          </label>
          <label>
            {t('sample.delivery.field.trackingNo')}
            <Input
              value={form.tracking_no}
              onChange={(event) => onFormChange({ ...form, tracking_no: event.target.value })}
            />
          </label>
        </div>
        <label>
          {t('sample.delivery.field.quotation')}
          <RemoteSelect
            allowClear
            ariaLabel={t('sample.delivery.field.quotation')}
            fetchOptions={fetchQuotations}
            placeholder={t('common.remoteSelect.placeholder')}
            value={form.quotation_id}
            initialOption={
              form.quotation_id && form.quotation_no
                ? { value: form.quotation_id, label: form.quotation_no }
                : undefined
            }
            onChange={handleQuotationChange}
          />
        </label>
        <div className="form-divider">{t('sample.delivery.modal.lineSection')}</div>
        <label>
          {t('sample.delivery.field.sampleRecord')}
          <RemoteSelect
            allowClear
            ariaLabel={t('sample.delivery.field.sampleRecord')}
            fetchOptions={fetchSampleRecords}
            placeholder={t('common.remoteSelect.placeholder')}
            value={form.sample_record_id}
            initialOption={
              form.sample_record_id
                ? {
                    value: form.sample_record_id,
                    label: [form.sample_code, form.product_name].filter(Boolean).join(' / '),
                  }
                : undefined
            }
            onChange={handleSampleRecordChange}
          />
        </label>
        <div className="form-pair two">
          <label>
            {t('sample.delivery.field.sampleCode')}
            <Input readOnly value={form.sample_code} />
          </label>
          <label>
            {t('sample.delivery.field.sampleType')}
            <Input readOnly value={sampleRecordTypeLabel(form.sample_type)} />
          </label>
        </div>
        <div className="form-pair two">
          <label>
            {t('sample.delivery.field.productCode')}
            <Input readOnly value={form.product_code} />
          </label>
          <label>
            {t('sample.delivery.field.productName')}
            <Input readOnly value={form.product_name} />
          </label>
        </div>
        <div className="form-pair two">
          <label>
            {t('sample.delivery.field.quantity')}
            <Input
              type="number"
              min="0.0001"
              step="0.0001"
              value={form.quantity}
              onChange={(event) => onFormChange({ ...form, quantity: event.target.value })}
            />
          </label>
          <label>
            {t('sample.delivery.field.unit')}
            <Input readOnly value={form.unit} />
          </label>
        </div>
        {selectedRecord?.stock_summary?.retained_quantity ? (
          <div className="form-hint">
            {t('sample.record.field.retainedQuantity')}
            {': '}
            {selectedRecord.stock_summary.retained_quantity} {selectedRecord.unit}
          </div>
        ) : null}
        <label>
          {t('sample.delivery.field.lineRemark')}
          <Input
            value={form.line_remark}
            onChange={(event) => onFormChange({ ...form, line_remark: event.target.value })}
          />
        </label>
        <div className="form-divider">{t('sample.delivery.modal.feeSection')}</div>
        <div className="form-pair two">
          <label htmlFor="sample-delivery-fee-type">
            {t('sample.delivery.field.feeType')}
            <FormSelect
              id="sample-delivery-fee-type"
              value={form.fee_type}
              onChange={(event) => onFormChange({ ...form, fee_type: event.target.value })}
            >
              {sampleDeliveryFeeTypeOptions.map((item) => (
                <option key={item.value} value={item.value}>
                  {t(item.labelKey)}
                </option>
              ))}
            </FormSelect>
          </label>
          <label>
            {t('sample.delivery.field.amount')}
            <Input
              type="number"
              min="0"
              step="0.01"
              value={form.fee_amount}
              onChange={(event) => onFormChange({ ...form, fee_amount: event.target.value })}
            />
          </label>
        </div>
        <div className="form-pair two">
          <label>
            {t('sample.delivery.field.currency')}
            <Input
              value={form.fee_currency}
              onChange={(event) => onFormChange({ ...form, fee_currency: event.target.value })}
            />
          </label>
          <label htmlFor="sample-delivery-fee-payer">
            {t('sample.delivery.field.payerType')}
            <FormSelect
              id="sample-delivery-fee-payer"
              value={form.fee_payer_type}
              onChange={(event) => onFormChange({ ...form, fee_payer_type: event.target.value })}
            >
              {sampleDeliveryPayerTypeOptions.map((item) => (
                <option key={item.value} value={item.value}>
                  {t(item.labelKey)}
                </option>
              ))}
            </FormSelect>
          </label>
        </div>
        <label>
          {t('sample.delivery.field.feeRemark')}
          <Input
            value={form.fee_remark}
            onChange={(event) => onFormChange({ ...form, fee_remark: event.target.value })}
          />
        </label>
        <label htmlFor="sample-delivery-remark">
          {t('sample.delivery.field.remark')}
          <Input.TextArea
            id="sample-delivery-remark"
            rows={2}
            value={form.remark}
            onChange={(event) => onFormChange({ ...form, remark: event.target.value })}
          />
        </label>
        <div className="modal-actions">
          <button className="secondary-inline" type="button" onClick={onClose}>
            {t('sample.delivery.action.cancel')}
          </button>
          {mode === 'edit' ? (
            <button
              className="inline-submit"
              disabled={submitting}
              type="button"
              onClick={onSaveDraft}
            >
              {t('sample.delivery.action.saveDraft')}
            </button>
          ) : (
            <button className="inline-submit" disabled={submitting} type="submit">
              {t('sample.delivery.action.create')}
            </button>
          )}
        </div>
      </form>
    </Modal>
  )
}
