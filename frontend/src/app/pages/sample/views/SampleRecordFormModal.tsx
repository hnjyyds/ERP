import { Input, Modal } from 'antd'
import type { FormEvent } from 'react'

import { t } from '@/app/appI18n'
import { FormSelect, RemoteSelect } from '@/shared/ui'
import {
  sampleRecordStatusOptions,
  sampleRecordTypeOptions,
  sampleSourceTypeOptions,
} from '@/shared/formOptions'
import { useSampleFormOptions } from '../hooks/useSampleFormOptions'
import type { SampleRecordFormState } from '../sampleRecordFormHelpers'

type Props = {
  open: boolean
  form: SampleRecordFormState
  submitting: boolean
  onFormChange: (form: SampleRecordFormState) => void
  onClose: () => void
  onSubmit: (event: FormEvent<HTMLFormElement>) => void
  onImport: () => void
}

export function SampleRecordFormModal({
  open,
  form,
  submitting,
  onFormChange,
  onClose,
  onSubmit,
  onImport,
}: Props) {
  const { fetchCustomers, fetchProducts, fetchSuppliers, getCustomer, getProduct, getSupplier } =
    useSampleFormOptions()

  function applyCustomer(customerId: string) {
    if (!customerId) {
      onFormChange({ ...form, customer_id: '', customer_name: '' })
      return
    }
    const customer = getCustomer(customerId)
    onFormChange({
      ...form,
      customer_id: customerId,
      customer_name:
        customer?.cn_name || customer?.en_name || customer?.code || form.customer_name,
    })
  }

  function applyProduct(productId: string) {
    if (!productId) {
      onFormChange({ ...form, product_id: '', product_code: '', product_name: '' })
      return
    }
    const product = getProduct(productId)
    onFormChange({
      ...form,
      product_id: productId,
      product_code: product?.code ?? '',
      product_name: product?.cn_name || product?.en_name || form.product_name,
    })
  }

  function applySupplier(supplierId: string) {
    if (!supplierId) {
      onFormChange({ ...form, supplier_id: '', supplier_name: '' })
      return
    }
    const supplier = getSupplier(supplierId)
    onFormChange({
      ...form,
      supplier_id: supplierId,
      supplier_name:
        supplier?.cn_name || supplier?.en_name || supplier?.code || form.supplier_name,
    })
  }

  return (
    <Modal
      centered
      footer={null}
      open={open}
      title={t('sample.record.modal.createTitle')}
      width={1040}
      onCancel={onClose}
    >
      <form className="record-form entity-modal-form sample-modal-form" onSubmit={onSubmit}>
        <label>
          {t('sample.record.field.code')}
          <Input
            readOnly
            value={form.code}
            placeholder={t('sample.record.form.codeAutoGenerated')}
          />
        </label>
        <label htmlFor="sample-record-type">
          {t('sample.record.field.sampleType')}
          <FormSelect
            id="sample-record-type"
            value={form.sample_type}
            onChange={(event) => onFormChange({ ...form, sample_type: event.target.value })}
          >
            {sampleRecordTypeOptions.map((item) => (
              <option key={item.value} value={item.value}>
                {t(item.labelKey)}
              </option>
            ))}
          </FormSelect>
        </label>
        <label htmlFor="sample-record-status">
          {t('sample.record.field.status')}
          <FormSelect
            id="sample-record-status"
            value={form.status}
            onChange={(event) => onFormChange({ ...form, status: event.target.value })}
          >
            {sampleRecordStatusOptions.map((item) => (
              <option key={item.value} value={item.value}>
                {t(item.labelKey)}
              </option>
            ))}
          </FormSelect>
        </label>
        <label>
          {t('sample.record.field.receivedQuantity')}
          <Input
            type="number"
            min="0.01"
            step="0.01"
            value={form.quantity}
            onChange={(event) => onFormChange({ ...form, quantity: event.target.value })}
          />
        </label>
        <label>
          {t('sample.record.field.receivedAt')}
          <Input
            type="date"
            value={form.received_at}
            onChange={(event) => onFormChange({ ...form, received_at: event.target.value })}
          />
        </label>
        <label>
          {t('sample.record.field.submittedAt')}
          <Input
            type="date"
            value={form.submitted_at}
            onChange={(event) => onFormChange({ ...form, submitted_at: event.target.value })}
          />
        </label>
        <label>
          {t('sample.record.field.product')}
          <RemoteSelect
            allowClear
            ariaLabel={t('sample.record.field.product')}
            fetchOptions={fetchProducts}
            placeholder={t('common.remoteSelect.placeholder')}
            value={form.product_id}
            initialOption={
              form.product_id
                ? {
                    value: form.product_id,
                    label: [form.product_code, form.product_name].filter(Boolean).join(' / '),
                  }
                : undefined
            }
            onChange={applyProduct}
          />
        </label>
        <label>
          {t('sample.record.field.customerSku')}
          <Input
            value={form.customer_sku}
            onChange={(event) => onFormChange({ ...form, customer_sku: event.target.value })}
          />
        </label>
        <label>
          {t('sample.record.field.supplierSku')}
          <Input
            value={form.supplier_sku}
            onChange={(event) => onFormChange({ ...form, supplier_sku: event.target.value })}
          />
        </label>
        <label>
          {t('sample.record.field.customer')}
          <RemoteSelect
            allowClear
            ariaLabel={t('sample.record.field.customer')}
            fetchOptions={fetchCustomers}
            placeholder={t('common.remoteSelect.placeholder')}
            value={form.customer_id}
            initialOption={
              form.customer_id && form.customer_name
                ? { value: form.customer_id, label: form.customer_name }
                : undefined
            }
            onChange={applyCustomer}
          />
        </label>
        <label>
          {t('sample.record.field.supplier')}
          <RemoteSelect
            allowClear
            ariaLabel={t('sample.record.field.supplier')}
            fetchOptions={fetchSuppliers}
            placeholder={t('common.remoteSelect.placeholder')}
            value={form.supplier_id}
            initialOption={
              form.supplier_id && form.supplier_name
                ? { value: form.supplier_id, label: form.supplier_name }
                : undefined
            }
            onChange={applySupplier}
          />
        </label>
        <label>
          {t('sample.record.field.purchaseContractNo')}
          <Input
            value={form.purchase_contract_no}
            onChange={(event) =>
              onFormChange({
                ...form,
                purchase_contract_no: event.target.value,
                purchase_contract_id: event.target.value,
              })
            }
          />
        </label>
        <label>
          {t('sample.record.field.unit')}
          <Input
            value={form.unit}
            onChange={(event) => onFormChange({ ...form, unit: event.target.value })}
          />
        </label>
        <label htmlFor="sample-record-source-type">
          {t('sample.record.field.sourceType')}
          <FormSelect
            id="sample-record-source-type"
            value={form.source_type}
            onChange={(event) => onFormChange({ ...form, source_type: event.target.value })}
          >
            {sampleSourceTypeOptions.map((item) => (
              <option key={item.value} value={item.value}>
                {t(item.labelKey)}
              </option>
            ))}
          </FormSelect>
        </label>
        <label>
          {t('sample.record.field.sourceCode')}
          <Input
            value={form.source_code}
            onChange={(event) => onFormChange({ ...form, source_code: event.target.value })}
          />
        </label>
        <label>
          {t('sample.record.field.description')}
          <Input.TextArea
            rows={3}
            value={form.description}
            onChange={(event) => onFormChange({ ...form, description: event.target.value })}
          />
        </label>
        <div className="form-divider">{t('sample.record.modal.imageSection')}</div>
        <label>
          {t('sample.record.field.imageFileId')}
          <Input
            value={form.image_file_id}
            onChange={(event) => onFormChange({ ...form, image_file_id: event.target.value })}
          />
        </label>
        <label>
          {t('sample.record.field.imageFilename')}
          <Input
            value={form.image_filename}
            onChange={(event) => onFormChange({ ...form, image_filename: event.target.value })}
          />
        </label>
        <label>
          {t('sample.record.field.imageUrl')}
          <Input
            value={form.image_url}
            onChange={(event) => onFormChange({ ...form, image_url: event.target.value })}
          />
        </label>
        <label>
          {t('sample.record.field.imageCaption')}
          <Input
            value={form.image_caption}
            onChange={(event) => onFormChange({ ...form, image_caption: event.target.value })}
          />
        </label>
        <div className="modal-actions">
          <button className="secondary-inline" type="button" onClick={onClose}>
            {t('sample.record.action.cancel')}
          </button>
          <button
            className="secondary-inline"
            disabled={submitting}
            type="button"
            onClick={onImport}
          >
            {t('sample.record.action.importFromForm')}
          </button>
          <button className="inline-submit" disabled={submitting} type="submit">
            {t('sample.record.action.create')}
          </button>
        </div>
      </form>
    </Modal>
  )
}
