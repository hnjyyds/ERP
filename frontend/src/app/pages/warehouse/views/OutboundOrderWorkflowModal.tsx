import { Alert, Button, Input, Modal } from 'antd'
import { CheckCircle2, PackagePlus, Send, Warehouse } from 'lucide-react'

import { outboundOrderModeOptions } from '@/shared/formOptions'
import { FormSelect, PanelTitle } from '@/shared/ui'
import { ApprovalAssigneeSelect } from '@/app/components/ApprovalAssigneeSelect'
import { t } from '@/app/appI18n'
import type { CurrentUser, OutboundOrder, OutboundPlan } from '@/api'

import { outboundPlanStatusLabel } from '../outboundOrderHelpers'
import type { useOutboundOrderWorkflow } from '../hooks/useOutboundOrderWorkflow'

type Props = {
  workflow: ReturnType<typeof useOutboundOrderWorkflow>
  outboundPlans: OutboundPlan[]
  selectedOrder: OutboundOrder | null
  currentUser: CurrentUser
}

export function OutboundOrderWorkflowModal({
  workflow,
  outboundPlans,
  selectedOrder,
  currentUser,
}: Props) {
  return (
    <Modal
      centered
      footer={null}
      open={workflow.outboundOrderModalOpen}
      title={t('warehouse.outboundOrder.form.modalTitle')}
      width={980}
      onCancel={workflow.closeOutboundOrderModal}
    >
      <div className="workflow-modal-content entity-modal-form">
        <PanelTitle
          icon={<Warehouse size={18} />}
          title={t('warehouse.outboundOrder.form.sectionTitle')}
        />
        <form className="record-form" onSubmit={workflow.generateOutboundOrder}>
          <div className="form-divider">{t('warehouse.outboundOrder.form.fromPlan')}</div>
          <label htmlFor="outbound-order-plan-id">
            {t('warehouse.outboundOrder.field.outboundPlan')}
            <FormSelect
              id="outbound-order-plan-id"
              required
              value={workflow.form.plan_id}
              onChange={(event) => workflow.handleOutboundOrderPlanChange(event.target.value)}
            >
              <option value="">{t('warehouse.outboundOrder.form.selectPlan')}</option>
              {outboundPlans.map((plan) => (
                <option key={plan.id} value={plan.id}>
                  {plan.code} / {plan.source_code} / {outboundPlanStatusLabel(plan.status)}
                </option>
              ))}
            </FormSelect>
          </label>
          <label htmlFor="outbound-order-code">
            {t('warehouse.outboundOrder.field.codeNo')}
            <Input
              id="outbound-order-code"
              readOnly
              value=""
              placeholder={t('warehouse.outboundOrder.form.codeAutoGenerated')}
            />
          </label>
          <div className="form-pair two">
            <label htmlFor="outbound-order-mode">
              {t('warehouse.outboundOrder.field.outboundMode')}
              <FormSelect
                id="outbound-order-mode"
                value={workflow.form.outbound_mode}
                onChange={(event) =>
                  workflow.setForm({ ...workflow.form, outbound_mode: event.target.value })
                }
              >
                {outboundOrderModeOptions.map((item) => (
                  <option key={item.value} value={item.value}>
                    {t(item.labelKey)}
                  </option>
                ))}
              </FormSelect>
            </label>
            <label htmlFor="outbound-order-date">
              {t('warehouse.outboundOrder.field.outboundAt')}
              <Input
                id="outbound-order-date"
                required
                type="date"
                value={workflow.form.outbound_at}
                onChange={(event) =>
                  workflow.setForm({ ...workflow.form, outbound_at: event.target.value })
                }
              />
            </label>
          </div>
          <div className="form-pair two">
            <label htmlFor="outbound-order-warehouse-id">
              {t('warehouse.outboundOrder.field.warehouseId')}
              <Input
                id="outbound-order-warehouse-id"
                required
                value={workflow.form.warehouse_id}
                onChange={(event) =>
                  workflow.setForm({ ...workflow.form, warehouse_id: event.target.value })
                }
              />
            </label>
            <label htmlFor="outbound-order-warehouse-name">
              {t('warehouse.outboundOrder.field.warehouse')}
              <Input
                id="outbound-order-warehouse-name"
                required
                value={workflow.form.warehouse_name}
                onChange={(event) =>
                  workflow.setForm({ ...workflow.form, warehouse_name: event.target.value })
                }
              />
            </label>
          </div>
          <div className="form-pair two">
            <label htmlFor="outbound-order-location-id">
              {t('warehouse.outboundOrder.field.locationId')}
              <Input
                id="outbound-order-location-id"
                required
                value={workflow.form.location_id}
                onChange={(event) =>
                  workflow.setForm({ ...workflow.form, location_id: event.target.value })
                }
              />
            </label>
            <label htmlFor="outbound-order-location-name">
              {t('warehouse.outboundOrder.field.location')}
              <Input
                id="outbound-order-location-name"
                required
                value={workflow.form.location_name}
                onChange={(event) =>
                  workflow.setForm({ ...workflow.form, location_name: event.target.value })
                }
              />
            </label>
          </div>
          <label htmlFor="outbound-order-operator">
            {t('warehouse.outboundOrder.field.operator')}
            <Input
              id="outbound-order-operator"
              required
              value={workflow.form.operator_name}
              onChange={(event) =>
                workflow.setForm({ ...workflow.form, operator_name: event.target.value })
              }
            />
          </label>
          <label htmlFor="outbound-exception-reason">
            {t('warehouse.outboundOrder.field.exceptionReason')}
            <Input.TextArea
              id="outbound-exception-reason"
              rows={3}
              value={workflow.form.exception_reason}
              onChange={(event) =>
                workflow.setForm({ ...workflow.form, exception_reason: event.target.value })
              }
            />
          </label>
          <Button
            disabled={!workflow.form.plan_id}
            htmlType="submit"
            icon={<PackagePlus size={16} />}
            loading={workflow.submitting}
          >
            {t('warehouse.outboundOrder.action.generate')}
          </Button>
        </form>

        <form
          className="record-form accessory-form generation-form"
          onSubmit={workflow.approveSelectedOutboundOrder}
        >
          <div className="form-divider">{t('warehouse.outboundOrder.form.submitSection')}</div>
          {selectedOrder?.status === 'draft' ? (
            <ApprovalAssigneeSelect
              currentUserId={currentUser.id}
              label={t('warehouse.outboundOrder.field.reviewer')}
              onChange={workflow.setReviewerId}
              requiredPermission="warehouse:outbound_order:approve"
              value={workflow.reviewerId}
            />
          ) : null}
          <Button
            disabled={!selectedOrder || selectedOrder.status !== 'draft' || !workflow.reviewerId}
            htmlType="button"
            icon={<Send size={16} />}
            loading={workflow.submitting}
            onClick={() => void workflow.submitSelectedOutboundOrder()}
          >
            {t('warehouse.outboundOrder.action.submit')}
          </Button>
          <div className="form-pair two">
            <label htmlFor="outbound-reviewer-name">
              {t('warehouse.outboundOrder.field.reviewer')}
              <Input id="outbound-reviewer-name" disabled value={selectedOrder?.reviewer_name ?? ''} />
            </label>
            <label htmlFor="outbound-approved-at">
              {t('warehouse.outboundOrder.field.approvedAt')}
              <Input
                id="outbound-approved-at"
                required
                type="date"
                value={workflow.approvalForm.approved_at}
                onChange={(event) =>
                  workflow.setApprovalForm({
                    ...workflow.approvalForm,
                    approved_at: event.target.value,
                  })
                }
              />
            </label>
          </div>
          <label className="checkbox-line" htmlFor="outbound-allow-negative">
            <input
              aria-label={t('warehouse.outboundOrder.field.allowNegative')}
              id="outbound-allow-negative"
              type="checkbox"
              checked={workflow.approvalForm.allow_negative}
              onChange={(event) =>
                workflow.setApprovalForm({
                  ...workflow.approvalForm,
                  allow_negative: event.target.checked,
                })
              }
            />
            {t('warehouse.outboundOrder.field.allowNegative')}
          </label>
          <Button
            disabled={
              !selectedOrder ||
              selectedOrder.status !== 'submitted' ||
              !workflow.canApproveSelectedOrder
            }
            htmlType="submit"
            icon={<CheckCircle2 size={16} />}
            loading={workflow.submitting}
            type="primary"
          >
            {t('warehouse.outboundOrder.action.approve')}
          </Button>
          {selectedOrder?.status === 'submitted' && !workflow.canApproveSelectedOrder ? (
            <Alert
              message={t('warehouse.outboundOrder.message.waitingApproval', {
                name:
                  selectedOrder.reviewer_name ??
                  t('warehouse.outboundOrder.detail.reviewerFallback'),
              })}
              showIcon
              type="info"
            />
          ) : null}
        </form>
      </div>
    </Modal>
  )
}
